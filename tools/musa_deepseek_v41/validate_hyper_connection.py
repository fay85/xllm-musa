"""Validate and time each production mHC binding on one idle MUSA GPU."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
from typing import Callable

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import torch
import torch_musa  # noqa: F401

from scripts.logger import logger
from tools.musa_deepseek_v41.validate_shared_swiglu import _timings
from xllm.python import initialize_runtime
from xllm.python.kernels_musa.hyper_connection import select_hyper_connection_ops


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path)
    args = parser.parse_args()
    if torch.musa.device_count() != 1:
        raise RuntimeError("Expose exactly one idle GPU")
    import musa_python_kernel_test_module as native

    sys.modules["xllm_runtime"] = native
    initialize_runtime()
    from xllm.python.models.deepseek_v41 import DeepseekV41Config, DeepseekV41HyperConnection, _hc_split_sinkhorn

    torch.manual_seed(111002)
    device = torch.device("musa:0")
    for part in ("PRE", "POST", "METADATA"):
        os.environ[f"XLLM_DSV41_MUSA_HC_{part}"] = "reference"
    cfg = DeepseekV41Config(hidden_size=5120, hc_mult=4, hc_sinkhorn_iters=20, hc_eps=1e-6)
    reference = DeepseekV41HyperConnection(cfg, torch.bfloat16, device)
    for part in ("PRE", "POST", "METADATA"):
        os.environ[f"XLLM_DSV41_MUSA_HC_{part}"] = "v4_fused"
    fused = select_hyper_connection_ops(device, torch.bfloat16, 4, 20, 1e-6)
    result = {
        "status": "RUNNING", "seed": 111002, "device": torch.musa.get_device_name(0),
        "scope": "one GPU production bindings; not 1P1D or full-model accuracy",
        "thresholds": {"bf16": {"rtol": 1 / 128, "atol": 1e-3}, "fp32": {"rtol": 2e-5, "atol": 1e-6}},
        "checks": [], "timings": [],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)

    def save() -> None:
        args.output.write_text(json.dumps(result, indent=2))

    def check(name: str, actual: torch.Tensor, expected: torch.Tensor) -> None:
        assert actual.device.type == "musa", "No host compute fallback"
        a, b = actual.cpu().float(), expected.cpu().float()
        tolerance = result["thresholds"]["fp32" if actual.dtype == torch.float32 else "bf16"]
        finite = torch.isfinite(a) & torch.isfinite(b)
        delta = (a[finite] - b[finite]).abs()
        row = {"name": name, "status": "CHECKING", "elements": a.numel(),
               "max_abs_error": delta.max().item() if delta.numel() else 0.0,
               "bitwise_equal": bool(torch.equal(a, b)), **tolerance}
        result["checks"].append(row)
        save()
        try:
            torch.testing.assert_close(a, b, equal_nan=False, **tolerance)
        except AssertionError:
            row["status"] = "FAIL"
            result["status"] = "FAIL"
            torch.save({"actual": a, "expected": b}, args.output.with_suffix(".failure.pt"))
            save()
            raise
        row["status"] = "PASS"
        save()

    def measure(name: str, tokens: int, old: Callable, new: Callable) -> None:
        old_time, new_time = _timings(old, 30), _timings(new, 30)
        result["timings"].append({"op": name, "tokens": tokens, "hidden": 5120,
                                  "reference": old_time, "fused": new_time,
                                  "wall_reduction_pct": 100 * (1 - new_time["median_wall_us"] / old_time["median_wall_us"])})
        save()

    with torch.inference_mode():
        for tokens in (0, 1, 17, 256, 2048):
            residual = torch.randn(tokens, 4, 10240, device=device, dtype=torch.bfloat16)[..., ::2]
            value = torch.randn(tokens, 10240, device=device, dtype=torch.bfloat16)[:, ::2]
            mixes = torch.randn(tokens, 48, device=device)[:, ::2]
            scale = torch.tensor([0.5, 1.0, 1.5], device=device)
            base = torch.randn(24, device=device) * 0.1
            pre, post, comb = _hc_split_sinkhorn(mixes, scale, base, 4, 20, 1e-6)
            # Deliberately different carried pre, to catch substitution of the
            # coefficients generated by this sublayer for the previous ones.
            carried_pre = torch.flip(pre, dims=(-1,)) + 0.125
            check(f"pre_T{tokens}", fused.pre(residual, carried_pre), reference.hc_pre(residual, carried_pre))
            check(f"post_T{tokens}", fused.post(value, residual, post, comb), reference.hc_post(value, residual, post, comb))
            metadata = fused.metadata(mixes, scale, base)
            for key, actual, expected in zip(("pre", "post", "comb"), metadata, (pre, post, comb)):
                check(f"metadata_{key}_T{tokens}", actual, expected)
            if tokens in (1, 256, 2048):
                r, x, mix = residual.contiguous(), value.contiguous(), mixes.contiguous()
                measure("pre", tokens, lambda: reference.hc_pre(r, carried_pre), lambda: fused.pre(r, carried_pre))
                measure("post", tokens, lambda: reference.hc_post(x, r, post, comb), lambda: fused.post(x, r, post, comb))
                measure("metadata", tokens, lambda: _hc_split_sinkhorn(mix, scale, base, 4, 20, 1e-6), lambda: fused.metadata(mix, scale, base))

        for iterations in (1, 2, 20):
            ops = select_hyper_connection_ops(device, torch.bfloat16, 4, iterations, 1e-6)
            mix = torch.randn(17, 24, device=device) * 30
            scale, base = torch.ones(3, device=device), torch.zeros(24, device=device)
            # Use an independent FP64 oracle for saturated logits. The MUSA
            # Torch composition itself differs by 4.6e-3 from CPU FP64 for
            # the captured iterations=1 case; the native kernel differs by
            # less than 2e-7. Preserve that diagnostic rather than weakening
            # the acceptance tolerance to match an inaccurate reference.
            oracle = _hc_split_sinkhorn(mix.cpu().double(), scale.cpu().double(), base.cpu().double(), 4, iterations, 1e-6)
            torch_reference = _hc_split_sinkhorn(mix, scale, base, 4, iterations, 1e-6)
            actual_values = ops.metadata(mix, scale, base)
            for key, actual, expected, gpu_reference in zip(("pre", "post", "comb"), actual_values, oracle, torch_reference):
                result.setdefault("saturated_reference_diagnostics", []).append({
                    "part": key, "iterations": iterations,
                    "torch_musa_vs_fp64_max_abs": (gpu_reference.cpu().double() - expected).abs().max().item(),
                    "native_vs_fp64_max_abs": (actual.cpu().double() - expected).abs().max().item(),
                })
                check(f"saturated_metadata_{key}_iters{iterations}", actual, expected)

        stream = torch.musa.Stream()
        with torch.musa.stream(stream):
            r = torch.randn(3, 4, 64, device=device, dtype=torch.bfloat16)
            x = torch.randn(3, 64, device=device, dtype=torch.bfloat16)
            mix, scale, base = torch.randn(3, 24, device=device), torch.ones(3, device=device), torch.zeros(24, device=device)
            p, q, c = _hc_split_sinkhorn(mix, scale, base, 4, 20, 1e-6)
            got = [fused.pre(r + 1, p), fused.post(x + 1, r, q, c), *fused.metadata(mix + 1, scale, base)]
            want = [reference.hc_pre(r + 1, p), reference.hc_post(x + 1, r, q, c), *_hc_split_sinkhorn(mix + 1, scale, base, 4, 20, 1e-6)]
        stream.synchronize()
        for index, (a, b) in enumerate(zip(got, want)):
            check(f"nondefault_stream_{index}", a, b)

        if args.checkpoint:
            from safetensors import safe_open

            weight_map = json.loads((args.checkpoint / "model.safetensors.index.json").read_text())["weight_map"]
            for layer in (0, 1, 14, 39):
                for part in ("attn", "ffn"):
                    weights = {}
                    for suffix in ("fn", "scale", "base"):
                        name = f"layers.{layer}.hc_{part}_{suffix}"
                        with safe_open(args.checkpoint / weight_map[name], framework="pt", device="cpu") as handle:
                            weights[suffix] = handle.get_tensor(name).to(device)
                    r = torch.randn(17, 4, 5120, device=device, dtype=torch.bfloat16)
                    flat = r.flatten(-2).float()
                    mix = reference._project_mixes(flat, weights["fn"]) * torch.rsqrt(flat.square().mean(-1, keepdim=True) + cfg.rms_norm_eps)
                    original = _hc_split_sinkhorn(mix, weights["scale"], weights["base"], 4, 20, 1e-6)
                    actual = fused.metadata(mix, weights["scale"], weights["base"])
                    for key, a, b in zip(("pre", "post", "comb"), actual, original):
                        check(f"checkpoint_layer{layer}_{part}_{key}", a, b)
                    value = torch.randn(17, 5120, device=device, dtype=torch.bfloat16)
                    pre, post, comb = original
                    check(f"checkpoint_layer{layer}_{part}_pre_combine", fused.pre(r, pre), reference.hc_pre(r, pre))
                    check(f"checkpoint_layer{layer}_{part}_post_combine", fused.post(value, r, post, comb), reference.hc_post(value, r, post, comb))
            result["checkpoint"] = str(args.checkpoint)
        result["status"] = "PASS"
        save()
        logger.info("mHC validation passed: %s checks, %s performance comparisons", len(result["checks"]), len(result["timings"]))


if __name__ == "__main__":
    main()
